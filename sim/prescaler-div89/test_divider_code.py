"""Netlist-level check of the divider code for the P = 8/9 prescaler (PR #161 review, issue #158).

Reads the committed `design/netlist/pll_top.spice` (generated by `klt netlist`) and checks, from the netlist itself
and not from arithmetic tables:

  1. the code tied on `XDIV` is M = 12, A = 4, i.e. N = 8*M + A = 100 (5.0 GHz at a 50 MHz reference);
  2. with the counter widths actually present in the netlist (`mcounter` M pins, `acounter` A pins), every N in
     90-110 has a legal code (A <= M, M >= 3 for the registered terminal count);
  3. the gate network of `acounter` (evaluated here as a zero-delay boolean model, parsed from the netlist) holds
     MC high for exactly A clocks after a load, for every A the width allows, then low (that is what makes
     N = 9*A + 8*(M - A) = 8*M + A with a P = 8/9 prescaler).

This is a logic check of the netlist, not a simulation result: no timing, no corner, no layout. Speed and corner
evidence for the counters is in `sim/divider-elab/` (simulated, nominal) and is a separate claim.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
NETLIST = os.path.join(HERE, "..", "..", "design", "netlist", "pll_top.spice")
P = 8
N_LO, N_HI, N_TARGET = 90, 110, 100
M_MIN = 3   # design/README.md: the registered terminal count assumes Q = 0001 is not the loaded value


def _read():
    with open(NETLIST) as f:
        return f.read().splitlines()


def subckts(lines):
    """{name: (pins, [instance token lists])} for every .subckt in the netlist."""
    out, cur = {}, None
    for ln in lines:
        t = ln.split()
        if not t or t[0].startswith(("*", "**")):
            continue
        if t[0].lower() == ".subckt":
            cur = (t[1], t[2:], [])
        elif t[0].lower() == ".ends" and cur:
            out[cur[0]] = (cur[1], cur[2])
            cur = None
        elif cur and t[0][0] in "Xx":
            cur[2].append(t)
    return out


def top_instance(lines, name):
    for ln in lines:
        t = ln.split()
        if t and t[0] == name:
            return t
    raise AssertionError("no %s instance in pll_top.spice" % name)


def tied_code():
    """(M, A, m_width, a_width) from the XDIV instance, using the divider's own pin order."""
    lines = _read()
    subs = subckts(lines)
    pins = subs["divider"][0]
    inst = top_instance(lines, "XDIV")
    conn = dict(zip(pins, inst[1:1 + len(pins)]))
    assert inst[1 + len(pins)] == "divider", "XDIV pin count does not match the divider subckt"
    mw = len([p for p in pins if re.fullmatch(r"M\d+", p)])
    aw = len([p for p in pins if re.fullmatch(r"A\d+", p)])

    def val(prefix, w):
        v = 0
        for i in range(w):
            net = conn["%s%d" % (prefix, i)]
            assert net in ("VDD", "VSS"), "%s%d is not tied to a rail (%s)" % (prefix, i, net)
            v |= (net == "VDD") << i
        return v
    return val("M", mw), val("A", aw), mw, aw


def test_tied_code_is_n100():
    m, a, mw, aw = tied_code()
    assert (m, a) == (12, 4), "tied M, A = %d, %d" % (m, a)
    assert P * m + a == N_TARGET


def test_every_n_90_110_reachable_with_netlist_widths():
    _, _, mw, aw = tied_code()
    codes = {}
    for m in range(M_MIN, 2 ** mw):
        for a in range(0, min(m, 2 ** aw - 1) + 1):
            codes.setdefault(P * m + a, (m, a))
    missing = [n for n in range(N_LO, N_HI + 1) if n not in codes]
    assert not missing, "unreachable with M %d bit, A %d bit: %s" % (mw, aw, missing)


def test_a_counter_width_is_3_bits():
    # A up to 7 is needed: N = 8*M + A with every residue 0-7 inside 90-110 (spec row 3, DR-005).
    assert tied_code()[3] == 3


def test_narrow_counter_would_be_flagged():
    # Negative control: with the old 2-bit A (A <= 3) N = 100 and N = 110 are NOT reachable at P = 8/9.
    codes = {P * m + a for m in range(M_MIN, 16) for a in range(0, min(m, 3) + 1)}
    assert N_TARGET not in codes and 110 not in codes


# --- boolean model of acounter, parsed from the netlist ---------------------------------------------------------
def _gate(kind, ins):
    if kind == "inv_hv":
        return int(not ins[0])
    if kind == "nand2_hv" or kind == "nand3_hv":
        return int(not all(ins))
    if kind == "nor2_hv":
        return int(not any(ins))
    raise AssertionError("unmodelled cell " + kind)


class ACounter:
    def __init__(self):
        subs = subckts(_read())
        self.pins, insts = subs["acounter"]
        self.flops, self.gates = [], []
        for t in insts:
            kind, nets = t[-1], t[1:-1]
            if kind == "dff_tg_hv":
                d, _ck, q = nets[:3]
                self.flops.append((d, q))
            else:
                n_in = {"inv_hv": 1, "nand2_hv": 2, "nand3_hv": 3, "nor2_hv": 2}[kind]
                self.gates.append((kind, nets[:n_in], nets[n_in]))
        self.state = {q: 0 for _, q in self.flops}

    def settle(self, ext):
        v = dict(ext); v.update(self.state); v["VDD"], v["VSS"] = 1, 0
        for _ in range(len(self.gates) + 2):
            for kind, ins, out in self.gates:
                if all(i in v for i in ins):
                    v[out] = _gate(kind, [v[i] for i in ins])
        return v

    def clock(self, ext):
        v = self.settle(ext)
        self.state = {q: v[d] for d, q in self.flops}


def _run_load(a_code, width, pre_state):
    c = ACounter()
    # arbitrary pre-state for every flop except MC, then one load clock (TC = 1), then free-run (TC = 0)
    for k, q in enumerate(sorted(q for _, q in c.flops if q != "MC")):
        c.state[q] = (pre_state >> k) & 1
    ext = {"CK": 0}
    for i in range(width):
        ext["A%d" % i] = (a_code >> i) & 1
    load = dict(ext, TC=1, TCN=0)
    hold = dict(ext, TC=0, TCN=1)
    c.clock(load)
    mc_hist = [c.state["MC"]]
    for _ in range(2 ** width + 3):
        c.clock(hold)
        mc_hist.append(c.state["MC"])
    return mc_hist, c


def test_acounter_mc_high_for_exactly_a_clocks():
    _, _, _, aw = tied_code()
    for a in range(2 ** aw):
        for pre in range(2 ** aw):
            hist, c = _run_load(a, aw, pre)
            assert sum(hist) == a, "A = %d (pre-state %d): MC history %s" % (a, pre, hist)
            assert hist[:a] == [1] * a and not any(hist[a:]), "A = %d: MC not a single run of A ones: %s" % (a, hist)
            assert all(v == 0 for k, v in c.state.items()), "counter did not hold at zero for A = %d" % a


