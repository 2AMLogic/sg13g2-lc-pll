#!/usr/bin/env python3
"""Generate the klt sim requests for the gate G2 C-grid (pinned VCO, with / without the prescaler on the tank).

Requires local IHP-Open-PDK v0.3.0 under `$PDK_ROOT/ihp-sg13g2/` (PDK_ROOT defaults to ~/share/pdk).
Run: scripts/fetch-vco.sh && python3 -I sim/corner-verification/vco-prescaler-load/make_requests.py
Reads the sha256-verified fetched VCO deck (.fetched/sg13g2-vco/design/vco.spice) and writes next to this file:
  vco_{unloaded,loaded}.spice,           circuit bodies (VCO netlist lines verbatim; only the supply and Vctrl
  vco_{unloaded,loaded}_dsubw.spice      sources become parameters, the differential probe BD is added; loaded adds
                                          the prescaler input X1 on OUTP/OUTN; _dsubw is the #173 varactor copy)
  sg13g2_inductor_em.spice, svar_dsubw125.spice   inductor-model copy and the local varactor subckt (netlist .include)
  request-{loaded,unloaded}-nominal.json, request-{loaded,unloaded}-stage{1,2}[-<shard>].json,
  request-{loaded,unloaded}-stage2-125C.json, request-{loaded,unloaded}-stage{1,2}-dsubw-<shard>.json
Stage 0 = nominal point only (TYP, 27 C, 3.3 V, Vctrl in {0, 1.65, 3.3} V), loaded and unloaded: the nominal G2
          bench (sim/vco-prescaler-load/README.md).
Stage 1 = 5 MOS x 3 MIM x 3 HBT x 3 T at 3.300 V (loaded: Vctrl 1.65 V only; no unloaded stage-1 grid).
Stage 2 = SLOW/TYP/FAST x 3 T x {2.970, 3.630} V, Vctrl in {0, 1.65, 3.3} V, loaded and unloaded.
"""
import hashlib
import json
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(ROOT / "sim"))
try:
    import corner_set
finally:
    sys.path.pop(0)

FETCHED = ROOT / ".fetched" / "sg13g2-vco"
VCO_SOURCE = FETCHED / "design" / "vco.spice"
SVAR_MODEL = "sg13g2_svaricaphv_mod.lib"
OSDI = "$PDK_ROOT/ihp-sg13g2/libs.tech/ngspice/osdi/"
TSTOP = "20n"

LOAD = """* The prescaler input on the tank (gate G1 load): instance, bias and start-up .ic as the retired local bench
* (source at commit 7d07c94; nominal record sim/vco-prescaler-load/records/20261103-123139-ce1d60d.md).
.include ../../../design/netlist/prescaler.spice
IRF vdd iref dc 50u
VMC mc 0 dc 0
X1 outp outn mc iref pdp pdn vdd 0 prescaler
.ic v(x1.hp)=3.2 v(x1.hn)=3.0 v(x1.x2.mp)=3.0 v(x1.x2.mn)=3.2
"""


def body(loaded, vco_lines=None):
    if vco_lines is None:
        vco_lines = VCO_SOURCE.read_text().splitlines()
    out = ["* sg13g2-lc-pll :: gate G2 C-grid circuit body (%s). Generated by make_requests.py from the sha256-verified" % ("loaded" if loaded else "unloaded"),
           "* fetched sg13g2-vco design/vco.spice: the VCO element lines are verbatim. Replaced: the VSUP / VCT DC values",
           "* (now .param vddv / vctrl axes) and the .ic common mode (tracks vddv). Removed: .lib/.include/.control (klt sim writes them).",
           "* Added: BD, the differential probe v(vd) = v(OUTP) - v(OUTN). Models: mosvar OSDI via options.osdi_preload.",
           ".param vddv=3.3 vctrl=1.65"]
    for ln in vco_lines:
        s = ln.strip()
        if s.startswith("*") or not s:
            continue
        if s.startswith(".control"):
            break
        if s.lower().startswith((".lib", ".include")):
            continue
        if s.startswith("VSUP "):
            out.append("VSUP VDD 0 dc {vddv}")
        elif s.startswith("VCT "):
            out.append("VCT VCTRL 0 dc {vctrl}")
        elif s.startswith(".ic"):
            out.append(".ic v(OUTP)={vddv+0.005} v(OUTN)={vddv-0.005}")
        elif s.startswith(".end"):
            continue
        else:
            out.append(ln)
    out.append("BD vd 0 V=v(outp)-v(outn)")
    out.append(".include sg13g2_inductor_em.spice")
    if loaded:
        out.append(LOAD.rstrip())
    return "\n".join(out) + "\n"


FAMILIES = ("mos", "mim", "hbt")  # the VCO holds HV MOS, MIM caps and HBTs


def sections(mos, mim, hbt, loaded=False):
    # the prescaler (22f2579) has rppd / rhigh instances: resistor corner follows the MIM corner name (typ/bcs/wcs)
    fam = FAMILIES + (("res",) if loaded else ())
    return corner_set.sections(fam, mos=mos, mim=mim, hbt=hbt, res=mim)


def req(tag, stage, shard=None, temps=tuple(corner_set.TEMPS), dsubw=False):
    loaded = tag == "loaded"
    comment = [
        "Gate G2 corner envelope, stage %d of the spec C-grid: pinned sg13g2-vco (unmodified) %s the prescaler input on the tank." % (stage, "with" if loaded else "without"),
        "Per corner: fosc_t40 = time of 30 periods of v(vd) = v(OUTP)-v(OUTN) (rising zero crossings 40 to 70, so f = 30 / fosc_t40); vpp = peak-to-peak over 10-%s; tst = first time v(vd) reaches +0.2 V from the 10 mV .ic kick (startup proxy, not the row 6 g_m / loss ratio)." % TSTOP,
        "No limits are set on the requests: the record grades row 1 (4.5-5.5 GHz), row 7 (>= 0.40 Vpp) and the loaded-vs-unloaded shift."]
    if dsubw:
        comment.append("APPROXIMATION (issue #173 operator ruling): the varactor subckt is a local copy (svar_dsubw125.spice) in which ONLY the dsubw diode card carries tnom = 125; "
                       "every unit, at any temperature, uses that card. No other card, deck or VCO line changes. Every 125 C number is an approximation, not the PDK card as shipped.")
    d = {"_comment": comment, "netlist": "vco_%s%s.spice" % (tag, "_dsubw" if dsubw else ""), "netlist_source": "schematic",
         "engine": "ngspice", "backend": "batch", "models": {"pdk": "ihp-sg13g2"},
         "analysis": {"kind": "tran", "args": "1p %s 0 2p" % TSTOP}}
    d["measurements"] = [
        {"name": "fosc_t40", "unit": "s", "spec_row": "1", "on_unreached": "null",
         "spice": ".meas tran fosc_t40 trig v(vd) val=0 rise=40 targ v(vd) val=0 rise=70"},
        {"name": "vpp", "unit": "V", "spec_row": "7",
         "spice": ".meas tran vpp pp v(vd) from=10n to=%s" % TSTOP},
        {"name": "tst", "unit": "s", "spec_row": "6", "on_unreached": "null",
         "spice": ".meas tran tst when v(vd)=0.2 rise=1"},
    ]
    if stage == 0:
        # nominal: mos_tt / cap_typ / hbt_typ, 27 C, 3.3 V, Vctrl = 0, 1.65, 3.3 V (the AC 1 loaded-vs-unloaded comparison)
        d["corners"] = {
            "process": [{"name": "TYP", "sections": sections(*corner_set.bundle("TYP", FAMILIES), loaded=loaded)}],
            "temperature_c": [27],
            "params": {"vddv": [corner_set.V_STAGE1] * 3, "vctrl": [0, 1.65, 3.3]},
        }
    elif stage == 1:
        d["corners"] = {
            "process": [{"name": "mos_%s/cap_%s/hbt_%s" % (m, c, h), "sections": sections(m, c, h, loaded)}
                        for m in corner_set.MOS for c in corner_set.MIM for h in corner_set.HBT
                        if shard in (None, m)],
            "temperature_c": list(temps),
            "params": {"vddv": [corner_set.V_STAGE1], "vctrl": [1.65]},
        }
    else:
        d["corners"] = {
            "process": [p for p in (
                {"name": b, "sections": sections(*corner_set.bundle(b, FAMILIES), loaded=loaded)}
                for b in corner_set.BUNDLES
            ) if shard in (None, p["name"])],
            "temperature_c": list(temps),
            # zipped, so the 6 (vddv, vctrl) pairs
            "params": {"vddv": [v for v in corner_set.V_STAGE2 for _ in range(3)], "vctrl": [0, 1.65, 3.3] * 2},
        }
    pre = [OSDI + "mosvar.osdi"] + ([OSDI + "psp103.osdi", OSDI + "r3_cmc.osdi"] if loaded else [])
    d["options"] = {"timeout_s": 900, "keep_artifacts": True, "osdi_preload": pre}
    return d


def dsubw_svar(raw=None, want=None, source_path=None):
    """Local copy of the PDK varactor subckt (sg13g2_svaricaphv_mod.lib, hash-pinned in sim/pins.json), renamed
    svar_loc / svar_loc_mod, with ONLY the dsubw diode card given tnom = 125 (the `rd` variant of 2AMLogic/sg13g2-vco#303)."""
    if raw is None:
        if source_path is None:
            pdk = Path(os.environ.get("PDK_ROOT") or Path.home() / "share" / "pdk")
            source_path = pdk / "ihp-sg13g2" / "libs.tech" / "ngspice" / "models" / SVAR_MODEL
        raw = Path(source_path).read_bytes()
    if want is None:
        pins = json.loads((ROOT / "sim" / "pins.json").read_text())
        want = pins["pdk"]["model_libs_sha256"][SVAR_MODEL]
    if hashlib.sha256(raw).hexdigest() != want:
        raise SystemExit("%s is not the pinned PDK file (sha256 != %s)" % (source_path or SVAR_MODEL, want))
    lines = raw.decode().splitlines()
    a = next(i for i, l in enumerate(lines) if l.startswith(".subckt sg13_hv_svaricap "))
    b = next(i for i, l in enumerate(lines) if l.startswith(".ends sg13_hv_svaricap"))
    out = ["* Local copy of the PDK varactor subckt sg13_hv_svaricap (sg13g2_svaricaphv_mod.lib, sha256 %s, lines %d-%d)." % (want, a + 1, b + 1),
           "* Generated by make_requests.py. Changes vs the PDK text: the subckt is renamed svar_loc, its mosvar model svar_loc_mod,",
           "* and the dsubw diode card gains `tnom = 125`. Nothing else (issue #173 operator ruling; the `rd` variant of sg13g2-vco#303)."]
    n = 0
    for l in lines[a:b + 1]:
        if l.startswith((".subckt", ".ends")):
            l = l.replace("sg13_hv_svaricap", "svar_loc")
        else:
            l = l.replace("sg13_hv_svaricap", "svar_loc_mod")
        if l.startswith(".model dsubw d "):
            l = l.replace(".model dsubw d ", ".model dsubw d tnom = 125 ", 1)
            n += 1
        out.append(l)
    assert n == 1, "expected exactly one dsubw model card"
    return "\n".join(out) + "\n"


def dsubw_body(loaded, vco_lines=None):
    b = body(loaded, vco_lines)
    assert " sg13_hv_svaricap " in b
    return b.replace(" sg13_hv_svaricap ", " svar_loc ") + ".include svar_dsubw125.spice\n"


def build_requests():
    # The whole stages describe the full grid. Shards fit the fleet's 3600 s ceiling.
    requests = {"request-loaded-stage1.json": req("loaded", 1)}
    for mos in corner_set.MOS:
        requests[f"request-loaded-stage1-{mos}.json"] = req("loaded", 1, mos)
        # Issue #173: every MOS shard covers 125 C, with a 27 C control in tt.
        temps = (27, 125) if mos == "tt" else (125,)
        requests[f"request-loaded-stage1-dsubw-{mos}.json"] = req("loaded", 1, mos, temps, dsubw=True)

    for tag in ("loaded", "unloaded"):
        requests[f"request-{tag}-nominal.json"] = req(tag, 0)
        requests[f"request-{tag}-stage2.json"] = req(tag, 2)
        requests[f"request-{tag}-stage2-125C.json"] = req(tag, 2, temps=(125,))
        for corner in corner_set.BUNDLES:
            requests[f"request-{tag}-stage2-{corner}.json"] = req(tag, 2, corner)
            requests[f"request-{tag}-stage2-dsubw-{corner}.json"] = req(tag, 2, corner, (27, 125), dsubw=True)
    return requests


def main():
    vco_lines = VCO_SOURCE.read_text().splitlines()
    varactor = dsubw_svar()
    inductor = FETCHED / "sim" / "inductor-model" / "sg13g2_inductor_em.spice"
    shutil.copyfile(inductor, HERE / inductor.name)
    (HERE / "svar_dsubw125.spice").write_text(varactor)
    for tag in ("unloaded", "loaded"):
        loaded = tag == "loaded"
        (HERE / f"vco_{tag}.spice").write_text(body(loaded, vco_lines))
        (HERE / f"vco_{tag}_dsubw.spice").write_text(dsubw_body(loaded, vco_lines))
    for name, request in build_requests().items():
        (HERE / name).write_text(json.dumps(request, indent=1) + "\n")


if __name__ == "__main__":
    main()
