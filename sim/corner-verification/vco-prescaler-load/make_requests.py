#!/usr/bin/env python3
"""Generate the klt sim requests for the gate G2 C-grid (pinned VCO, with / without the prescaler on the tank).

Run: scripts/fetch-vco.sh && python3 -I sim/corner-verification/vco-prescaler-load/make_requests.py
Reads the sha256-verified fetched VCO deck (.fetched/sg13g2-vco/design/vco.spice) and writes next to this file:
  vco_unloaded.spice, vco_loaded.spice   circuit bodies (VCO netlist lines verbatim; only the supply and Vctrl
                                         sources become parameters, the differential probe BD is added; loaded adds
                                         the prescaler input X1 on OUTP/OUTN)
  sg13g2_inductor_em.spice               copy of the fetched, sha256-pinned inductor model (netlist .include)
  request-{loaded,unloaded}-stage{1,2}.json
Stage 1 = 5 MOS x 3 MIM x 3 HBT x 3 T at 3.300 V (loaded: Vctrl 1.65 V only; unloaded: not requested, the nominal
          unloaded point is in sim/vco-prescaler-load).
Stage 0 = nominal point only (TYP, 27 C, 3.3 V, Vctrl in {0, 1.65, 3.3} V), loaded and unloaded.
Stage 2 = SLOW/TYP/FAST x 3 T x {2.970, 3.630} V, Vctrl in {0, 1.65, 3.3} V, loaded and unloaded.
"""
import json
import os
import re
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
FETCHED = os.path.join(ROOT, ".fetched", "sg13g2-vco")
LIB = "libs.tech/ngspice/models/"
OSDI = "$PDK_ROOT/ihp-sg13g2/libs.tech/ngspice/osdi/"
MOS = ["tt", "ss", "ff", "sf", "fs"]
MIM = ["typ", "bcs", "wcs"]
HBT = ["typ", "bcs", "wcs"]
TSTOP = "20n"

LOAD = """* The prescaler input on the tank (gate G1 load): same instance, bias and start-up .ic as sim/vco-prescaler-load.
.include ../../../design/netlist/prescaler.spice
IRF vdd iref dc 50u
VMC mc 0 dc 0
X1 outp outn mc iref pdp pdn vdd 0 prescaler
.ic v(x1.hp)=3.2 v(x1.hn)=3.0 v(x1.x2.mp)=3.0 v(x1.x2.mn)=3.2
"""


def body(loaded):
    src = open(os.path.join(FETCHED, "design", "vco.spice")).read().splitlines()
    out = ["* sg13g2-lc-pll :: gate G2 C-grid circuit body (%s). Generated by make_requests.py from the sha256-verified" % ("loaded" if loaded else "unloaded"),
           "* fetched sg13g2-vco design/vco.spice: the VCO element lines are verbatim. Replaced: the VSUP / VCT DC values",
           "* (now .param vddv / vctrl axes) and the .ic common mode (tracks vddv). Removed: .lib/.include/.control (klt sim writes them).",
           "* Added: BD, the differential probe v(vd) = v(OUTP) - v(OUTN). Models: mosvar OSDI via options.osdi_preload.",
           ".param vddv=3.3 vctrl=1.65"]
    for ln in src:
        s = ln.strip()
        if s.startswith("*") or not s:
            continue
        if s.startswith(".control"):
            break
        if s.lower().startswith((".lib", ".include")):
            continue
        if s.startswith("VSUP "):
            out.append("VSUP VDD 0 dc {vddv}")
        elif s.startswith("VCT "):
            out.append("VCT VCTRL 0 dc {vctrl}")
        elif s.startswith(".ic"):
            out.append(".ic v(OUTP)={vddv+0.005} v(OUTN)={vddv-0.005}")
        elif s.startswith(".end"):
            continue
        else:
            out.append(ln)
    out.append("BD vd 0 V=v(outp)-v(outn)")
    out.append(".include sg13g2_inductor_em.spice")
    if loaded:
        out.append(LOAD.rstrip())
    return "\n".join(out) + "\n"


def sections(mos, mim, hbt, loaded=False):
    s = [
        {"lib": LIB + "cornerMOShv.lib", "section": "mos_" + mos},
        {"lib": LIB + "cornerCAP.lib", "section": "cap_" + mim},
        {"lib": LIB + "cornerHBT.lib", "section": "hbt_" + hbt},
    ]
    if loaded:
        # the prescaler (22f2579) has rppd / rhigh instances: resistor corner follows the MIM corner name (typ/bcs/wcs)
        s.append({"lib": LIB + "cornerRES.lib", "section": "res_" + mim})
    return s


def req(tag, stage, shard=None, temps=(-40, 27, 125)):
    loaded = tag == "loaded"
    comment = [
        "Gate G2 corner envelope, stage %d of the spec C-grid: pinned sg13g2-vco (unmodified) %s the prescaler input on the tank." % (stage, "with" if loaded else "without"),
        "Per corner: fosc_t40 = time of 30 periods of v(vd) = v(OUTP)-v(OUTN) (rising zero crossings 40 to 70, so f = 30 / fosc_t40); vpp = peak-to-peak over 10-%s; tst = first time v(vd) reaches +0.2 V from the 10 mV .ic kick (startup proxy, not the row 6 g_m / loss ratio)." % TSTOP,
        "No limits are set on the requests: the record grades row 1 (4.5-5.5 GHz), row 7 (>= 0.40 Vpp) and the loaded-vs-unloaded shift."]
    d = {"_comment": comment, "netlist": "vco_%s.spice" % tag, "netlist_source": "schematic",
         "engine": "ngspice", "backend": "batch", "models": {"pdk": "ihp-sg13g2"},
         "analysis": {"kind": "tran", "args": "1p %s 0 2p" % TSTOP}}
    d["measurements"] = [
        {"name": "fosc_t40", "unit": "s", "spec_row": "1", "on_unreached": "null",
         "spice": ".meas tran fosc_t40 trig v(vd) val=0 rise=40 targ v(vd) val=0 rise=70"},
        {"name": "vpp", "unit": "V", "spec_row": "7",
         "spice": ".meas tran vpp pp v(vd) from=10n to=%s" % TSTOP},
        {"name": "tst", "unit": "s", "spec_row": "6", "on_unreached": "null",
         "spice": ".meas tran tst when v(vd)=0.2 rise=1"},
    ]
    if stage == 0:
        # nominal: mos_tt / cap_typ / hbt_typ, 27 C, 3.3 V, Vctrl = 0, 1.65, 3.3 V (the AC 1 loaded-vs-unloaded comparison)
        d["corners"] = {
            "process": [{"name": "TYP", "sections": sections("tt", "typ", "typ", loaded)}],
            "temperature_c": [27],
            "params": {"vddv": [3.3] * 3, "vctrl": [0, 1.65, 3.3]},
        }
    elif stage == 1:
        d["corners"] = {
            "process": [{"name": "mos_%s/cap_%s/hbt_%s" % (m, c, h), "sections": sections(m, c, h, loaded)}
                        for m in MOS for c in MIM for h in HBT if shard in (None, m)],
            "temperature_c": list(temps),
            "params": {"vddv": [3.3], "vctrl": [1.65]},
        }
    else:
        d["corners"] = {
            "process": [p for p in (
                {"name": "SLOW", "sections": sections("ss", "wcs", "wcs", loaded)},
                {"name": "TYP", "sections": sections("tt", "typ", "typ", loaded)},
                {"name": "FAST", "sections": sections("ff", "bcs", "bcs", loaded)},
            ) if shard in (None, p["name"])],
            "temperature_c": list(temps),
            "params": {"vddv": [2.97] * 3 + [3.63] * 3, "vctrl": [0, 1.65, 3.3] * 2},  # zipped, so the 6 (vddv, vctrl) pairs
        }
    pre = [OSDI + "mosvar.osdi"] + ([OSDI + "psp103.osdi", OSDI + "r3_cmc.osdi"] if loaded else [])
    d["options"] = {"timeout_s": 900, "keep_artifacts": True, "osdi_preload": pre}
    return d


def main():
    shutil.copyfile(os.path.join(FETCHED, "sim", "inductor-model", "sg13g2_inductor_em.spice"),
                    os.path.join(HERE, "sg13g2_inductor_em.spice"))
    for tag in ("unloaded", "loaded"):
        with open(os.path.join(HERE, "vco_%s.spice" % tag), "w") as f:
            f.write(body(tag == "loaded"))
    # Whole-stage requests (the full grid) plus the shard files that were actually submitted: a whole-job
    # ceiling of 3600 s on the fleet and ~820 s per corner mean one 54-unit job is killed (see README).
    # Stage 2 shards by process corner (18 units), stage 1 by MOS corner (27 units).
    jobs = [("loaded", 1, None), ("loaded", 2, None), ("unloaded", 2, None)]
    jobs += [("loaded", 2, p) for p in ("SLOW", "TYP", "FAST")] + [("unloaded", 2, p) for p in ("SLOW", "TYP", "FAST")]
    jobs += [("loaded", 1, m) for m in MOS]
    for tag, stage, shard in jobs:
        name = "request-%s-stage%d%s.json" % (tag, stage, "" if shard is None else "-" + shard)
        with open(os.path.join(HERE, name), "w") as f:
            json.dump(req(tag, stage, shard), f, indent=1)
            f.write("\n")


def nominal():
    for tag in ("loaded", "unloaded"):
        with open(os.path.join(HERE, "request-%s-nominal.json" % tag), "w") as f:
            json.dump(req(tag, 0), f, indent=1)
            f.write("\n")


def extra():
    # 125 C only, stage 2: the whole-stage jobs returned -40 C and 27 C and lost the 125 C units at the fleet ceiling.
    for tag in ("loaded", "unloaded"):
        with open(os.path.join(HERE, "request-%s-stage2-125C.json" % tag), "w") as f:
            json.dump(req(tag, 2, None, (125,)), f, indent=1)
            f.write("\n")


main()
extra()
nominal()
