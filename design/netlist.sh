#!/usr/bin/env bash
# sg13g2-lc-pll :: derive the committed SPICE netlists under design/netlist/ from the
# xschem schematics, through `klt netlist` (never raw xschem: klt forces the headless
# flags and kills a hung run).
#
#   design/netlist.sh            regenerate design/netlist/<block>.spice
#   design/netlist.sh --check    regenerate into a temp dir and diff; exit 1 if stale
#   design/netlist.sh cp         one block only
#
# Needs klt and the SG13G2 PDK (PDK_ROOT = parent of ihp-sg13g2/; default ~/share/pdk).
# The exact klt command for one block is:
#   PDK=ihp-sg13g2 klt netlist --backend local --block --rcfile design/xschemrc \
#       -o <out>.spice design/<block>.sch
# followed by rewriting the absolute `** sch_path:` / `** sym_path:` stamp comments to
# repo-relative form, so the committed bytes do not depend on which checkout made them.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BLOCKS=(cp)
CHECK=0
SEL=()
for a in "$@"; do
  case "$a" in
    --check) CHECK=1 ;;
    -h|--help) sed -n '2,15p' "${BASH_SOURCE[0]}"; exit 0 ;;
    -*) echo "netlist.sh: unknown option $a" >&2; exit 2 ;;
    *) SEL+=("$a") ;;
  esac
done
[ "${#SEL[@]}" -gt 0 ] || SEL=("${BLOCKS[@]}")
command -v klt >/dev/null || { echo "netlist.sh: klt not found on PATH" >&2; exit 1; }

if [ -z "${PDK_ROOT:-}" ]; then
  for c in "${HOME}/share/pdk" /usr/share/pdk /usr/local/share/pdk; do
    [ -d "${c}/ihp-sg13g2/libs.tech/xschem" ] && { PDK_ROOT="${c}"; break; }
  done
fi
[ -n "${PDK_ROOT:-}" ] || { echo "netlist.sh: no ihp-sg13g2 install; set PDK_ROOT" >&2; exit 1; }
export PDK_ROOT PDK=ihp-sg13g2

TMP="$(mktemp -d)"; trap 'rm -rf "${TMP}"' EXIT
rc=0
for blk in "${SEL[@]}"; do
  [ -f "${HERE}/${blk}.sch" ] || { echo "netlist.sh: no schematic design/${blk}.sch" >&2; exit 1; }
  # klt runs from the repo root so the stamps it writes resolve against design/.
  ( cd "${HERE}/.." && klt netlist --backend local --block --rcfile design/xschemrc \
      -o "${TMP}/${blk}.raw" "design/${blk}.sch" >"${TMP}/${blk}.klt.log" 2>&1 ) \
    || { cat "${TMP}/${blk}.klt.log" >&2; echo "netlist.sh: klt netlist failed for ${blk}" >&2; exit 1; }
  {
    echo "* sg13g2-lc-pll :: ${blk} -- generated by design/netlist.sh (klt netlist) from design/${blk}.sch"
    echo "* do not edit by hand."
    sed -E 's#^(\*\* (sch|sym)_path: ).*/design/#\1design/#' "${TMP}/${blk}.raw"
  } >"${TMP}/${blk}.spice"
  grep -qE "^\.subckt +${blk}( |\$)" "${TMP}/${blk}.spice" || { echo "netlist.sh: .subckt ${blk} missing" >&2; exit 1; }
  if grep -E '^\.subckt ' "${TMP}/${blk}.spice" | grep -qE '\bnet[0-9]+\b'; then
    echo "netlist.sh: auto-generated net name in a .subckt port list (unresolved label)" >&2; exit 1
  fi
  if [ "${CHECK}" = 1 ]; then
    if diff -u --label "design/netlist/${blk}.spice (committed)" --label "design/${blk}.sch (regenerated)" \
         "${HERE}/netlist/${blk}.spice" "${TMP}/${blk}.spice"; then
      echo "ok  design/netlist/${blk}.spice matches design/${blk}.sch"
    else
      echo "STALE: design/netlist/${blk}.spice differs from design/${blk}.sch; run design/netlist.sh" >&2; rc=1
    fi
  else
    mkdir -p "${HERE}/netlist"; cp "${TMP}/${blk}.spice" "${HERE}/netlist/${blk}.spice"
    echo "netlisted ${blk} -> design/netlist/${blk}.spice"
  fi
done
exit "${rc}"
