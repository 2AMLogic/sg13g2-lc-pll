#!/usr/bin/env python3
"""Deck / request generator and analyzer for the lock-detector 50 MHz re-grade (sim/lock-detector).

Used by scripts/run-lock-detector.sh; run with `python3 -I`. Three subcommands:

  body    write the circuit body + the measurement list (one source of truth for the local
          nominal run and the klt sim C-grid request)
  request write a `klt sim` request for the C-grid (stage 1 or stage 2) around that body
  analyze turn {measurement name: value} into the record tables and the verdict

The bench never modifies the pinned lock_detector: it holds the integrator node VWIN with an ideal
source (named through the flattened hierarchical node xld.vwin) so that the slow (microsecond) RC
state does not have to settle, and integrates the current the cell sources into that node over one
reference cycle per (VWIN, phase-error) point. The equilibrium VWIN of the real closed loop is the
VWIN at which that net current is zero.
"""
import argparse, json, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "sim"))
import corner_set  # noqa: E402  (the spec C-grid, defined once in sim/corner_set.py)

T_PS = 20000                       # T_ref = 20 ns (50 MHz)
PHI_PS = [-10000, -8000, -6000, -4000, -2000, 0, 500, 1000, 2000, 3000, 4000, 5000, 5500, 6000,
          6500, 7000, 7500, 8000, 9000, 10000]
VH = [1.0, 1.5, 2.0, 2.5, 3.0]     # held VWIN grid (V)
VMID = 2                           # index in VH where the (VWIN-independent) pulse widths are measured
CYC = 3                            # cycles per segment: 0 and 1 settle, cycle 2 is measured
T0_PS = 20000
RAMP_NS = 400                      # Schmitt trip ramp: 3.3 -> 0 -> 3.3, RAMP_NS each way
FIXED_V = 3.3                      # the ramp is in absolute volts, from/to this value


def schedule(vh=VH, phi=PHI_PS):
    segs = []
    for vi, v in enumerate(vh):
        order = phi if vi % 2 == 0 else list(reversed(phi))
        for p in order:
            segs.append((vi, v, phi.index(p), p))
    return segs


def seg_t0(s):
    return T0_PS + s * CYC * T_PS


def win(s, p):
    a = seg_t0(s) + 2 * T_PS + min(0, p) - 1000
    return a, a + T_PS


def ramp_start(nseg):
    return T0_PS + nseg * CYC * T_PS + 2 * T_PS


def meas_list():
    """[(name, spice card, unit)]"""
    segs = schedule()
    out = []
    for s, (vi, v, pj, p) in enumerate(segs):
        a, b = win(s, p)
        out.append((f"q_{vi}_{pj}", f".meas tran q_{vi}_{pj} INTEG i(vh) FROM={a}p TO={b}p", "C"))
        if vi == VMID:
            for nm, node in (("err", "xld.err"), ("up", "up"), ("dn", "dn"), ("wide", "xld.wide"), ("errd", "xld.errd")):
                out.append((f"w{nm}_{pj}", f".meas tran w{nm}_{pj} INTEG v({node}) FROM={a}p TO={b}p", "Vs"))
            out.append((f"wmax_{pj}", f".meas tran wmax_{pj} MAX v(xld.wide) FROM={a}p TO={b}p", "V"))
            out.append((f"dmax_{pj}", f".meas tran dmax_{pj} MAX v(xld.errd) FROM={a}p TO={b}p", "V"))
            if p == max(PHI_PS):
                out.append(("twin_r", f".meas tran twin_r TRIG v(xld.err) VAL='vsup/2' RISE=1 TD={a}p TARG v(xld.errd) VAL='vsup/2' RISE=1 TD={a}p", "s"))
                out.append(("twin_f", f".meas tran twin_f TRIG v(xld.err) VAL='vsup/2' FALL=1 TD={a}p TARG v(xld.errd) VAL='vsup/2' FALL=1 TD={a}p", "s"))
    r0 = ramp_start(len(segs))
    r1 = r0 + RAMP_NS * 1000
    r2 = r1 + 40000 + RAMP_NS * 1000
    out.append(("vt_lock_rise_t", f".meas tran vt_lock_rise_t WHEN v(lock)='vsup/2' RISE=1 TD={r0}p", "s"))
    out.append(("vt_lock_fall_t", f".meas tran vt_lock_fall_t WHEN v(lock)='vsup/2' FALL=1 TD={r0}p", "s"))
    return out, r0, r1, r2


def tstop():
    _, _, _, r2 = meas_list()
    return r2 + 40000


def body(path_meas):
    segs = schedule()
    _, r0, r1, r2 = meas_list()
    L = []
    L.append("* sg13g2-lc-pll :: sim/lock-detector -- pinned PFD driving the pinned lock_detector at 50 MHz, VWIN held.")
    L.append("* Generated by scripts/ld_tool.py; do not edit. Circuit body: the model libraries, OSDI preloads, .tran and")
    L.append("* .meas cards are added by the runner (local) or by klt sim (C-grid).")
    L.append(".param vsup=3.3")
    L.append(".global sub!")
    L.append("VSUB sub! 0 0")
    L.append("VDD vdd 0 {vsup}")
    L.append("VREF ref 0 PULSE(0 {vsup} 20n 100p 100p 4.9n 20n)")
    # FB: one rising edge per cycle, delayed by phi relative to REF
    fb = ["VFB fb 0 PWL(0 0"]
    for s, (vi, v, pj, p) in enumerate(segs):
        for c in range(CYC):
            t = seg_t0(s) + c * T_PS + p
            fb.append(f"+ {t}p 0 {t + 100}p {{vsup}} {t + 5000}p {{vsup}} {t + 5100}p 0")
    t = r0 - 2 * T_PS
    while t < r2 + 40000:
        fb.append(f"+ {t}p 0 {t + 100}p {{vsup}} {t + 5000}p {{vsup}} {t + 5100}p 0")
        t += T_PS
    fb.append("+ )")
    L += fb
    # VWIN hold: per-V block level, then the Schmitt ramp
    h = ["VH xld.vwin 0 PWL(0 %g" % VH[0]]
    last = VH[0]
    for s, (vi, v, pj, p) in enumerate(segs):
        if v != last:
            t = seg_t0(s)
            h.append(f"+ {t}p {last} {t + 200}p {v}")
            last = v
    h.append(f"+ {r0 - 40000}p {last} {r0 - 39000}p {FIXED_V}")
    h.append(f"+ {r0}p {FIXED_V} {r1}p 0 {r1 + 40000}p 0 {r2}p {FIXED_V} {r2 + 40000}p {FIXED_V})")
    L += h
    L.append(".include .fetched/sg13g2-pll/design/netlist/pfd.spice")
    L.append(".include .fetched/sg13g2-pll/design/netlist/lock_detector.spice")
    L.append("XPFD ref fb up dn vdd 0 pfd")
    L.append("XLD up dn lock vdd 0 lock_detector")
    L.append(".options reltol=1e-3 abstol=1e-10 vntol=1e-5 chgtol=1e-14")
    open(path_meas, "w").write("\n".join(L) + "\n")


def cmd_body(a):
    body(a.out)
    ms, _, _, _ = meas_list()
    open(a.meas, "w").write("\n".join(m[1] for m in ms) + "\n")
    json.dump([{"name": n, "spice": c, "unit": u} for n, c, u in ms], open(a.meas_json, "w"))
    print(tstop())


# pfd + lock_detector hold HV MOS, MIM caps and poly resistors; no HBT. The MIM
# corner also picks the poly-resistor corner of the same grid point.
FAMILIES = ("mos", "mim", "res")


def process_bundles(stage, pdk):
    lib = f"{pdk}/ihp-sg13g2/{corner_set.LIB}"
    if stage == 1:
        return [{"name": f"mos_{mos}-{k}",
                 "sections": corner_set.sections(FAMILIES, lib=lib, mos=mos, mim=k, res=k)}
                for mos in corner_set.MOS for k in corner_set.MIM]
    return [{"name": b, "sections": corner_set.bundle_sections(b, FAMILIES, lib=lib)}
            for b in corner_set.BUNDLES]


def cmd_request(a):
    ms, _, _, _ = meas_list()
    req = {
        "netlist": a.body, "engine": "ngspice", "backend": "batch",
        "corners": {"process": process_bundles(a.stage, "$PDK_ROOT"), "temperature_c": list(corner_set.TEMPS)},
        "analysis": {"kind": "tran", "args": f"50p {tstop()}p 0 50p"},
        "measurements": [{"name": n, "spice": c, "unit": u} for n, c, u in ms],
        "options": {"timeout_s": 1500, "stage_model_inputs": True, "keep_artifacts": False,
                    "ngspice_init": ["set ngbehavior=hsa"],
                    "osdi_preload": ["$PDK_ROOT/ihp-sg13g2/libs.tech/ngspice/osdi/psp103.osdi",
                                     "$PDK_ROOT/ihp-sg13g2/libs.tech/ngspice/osdi/r3_cmc.osdi"]},
    }
    # one unit is ~10 minutes of ngspice; the fleet kills a job at 3600 s, so shard 2 units per job
    req["batch"] = {"max_units_per_job": 2, "max_concurrent_jobs": 6}
    if a.stage == 2:
        req["corners"]["params"] = {"vsup": list(corner_set.V_STAGE2)}
    else:
        req["corners"]["params"] = {"vsup": [corner_set.V_STAGE1]}
    json.dump(req, open(a.out, "w"), indent=1)


def interp_root(xs, ys, y0):
    """first x where the piecewise-linear y(x) crosses y0 (xs ascending); None if no crossing."""
    for i in range(1, len(xs)):
        y1, y2 = ys[i - 1], ys[i]
        if (y1 - y0) * (y2 - y0) <= 0 and y1 != y2:
            return xs[i - 1] + (y0 - y1) * (xs[i] - xs[i - 1]) / (y2 - y1)
    return None


def analyze_one(m, vsup):
    """m: {name: value}. Returns a dict of derived numbers (None where not derivable)."""
    r = {}
    r["I"] = {}                                     # (vi, pj) -> uA
    for vi in range(len(VH)):
        for pj in range(len(PHI_PS)):
            k = f"q_{vi}_{pj}"
            if k in m:
                r["I"][(vi, pj)] = m[k] / (T_PS * 1e-12) * 1e6
    # Schmitt trip voltages from the ramp (known linear ramps)
    _, r0, r1, r2 = meas_list()
    sl = FIXED_V / (RAMP_NS * 1e-9)
    tr, tf = m.get("vt_lock_rise_t"), m.get("vt_lock_fall_t")
    # LOCK rises while VWIN ramps down (first ramp), falls while it ramps up (second ramp)
    r["vt_dn"] = FIXED_V - (tr - r0 * 1e-12) * sl if tr is not None and tr < r1 * 1e-12 + 40e-9 else None
    r["vt_up"] = (tf - (r1 + 40000) * 1e-12) * sl if tf is not None and tf > (r1 + 40000) * 1e-12 else None
    r["twin_r"], r["twin_f"] = m.get("twin_r"), m.get("twin_f")
    r["wid"] = {pj: {k: m.get(f"w{k}_{pj}") for k in ("err", "up", "dn", "wide", "errd")} for pj in range(len(PHI_PS))}
    r["wmax"] = {pj: m.get(f"wmax_{pj}") for pj in range(len(PHI_PS))}
    r["dmax"] = {pj: m.get(f"dmax_{pj}") for pj in range(len(PHI_PS))}
    # I_net(V = trip) per phase, by linear interpolation in the held-V grid
    def inet_at(pj, v):
        ys = [r["I"].get((vi, pj)) for vi in range(len(VH))]
        if any(y is None for y in ys) or v is None:
            return None
        if v <= VH[0]:
            return ys[0]
        for i in range(1, len(VH)):
            if v <= VH[i]:
                return ys[i - 1] + (v - VH[i - 1]) * (ys[i] - ys[i - 1]) / (VH[i] - VH[i - 1])
        return ys[-1]
    r["inet_trip"] = {"up": [inet_at(pj, r["vt_up"]) for pj in range(len(PHI_PS))],
                      "dn": [inet_at(pj, r["vt_dn"]) for pj in range(len(PHI_PS))]}
    # V_eq(phi): root of I_net(V) (VWIN where the cell sources zero net current)
    veq = []
    for pj in range(len(PHI_PS)):
        ys = [r["I"].get((vi, pj)) for vi in range(len(VH))]
        if any(y is None for y in ys):
            veq.append(None); continue
        if ys[-1] > 0:
            veq.append(">%g" % VH[-1])
        elif ys[0] < 0:
            veq.append("<%g" % VH[0])
        else:
            veq.append(interp_root(VH, ys, 0.0))
    r["veq"] = veq
    # thresholds in phi (ps): for each side, where I_net(V_trip) crosses zero between the grid phi points
    def phi_cross(key, side):
        pts = [(p, y) for p, y in zip(PHI_PS, r["inet_trip"][key]) if y is not None and ((side > 0 and p >= 0) or (side < 0 and p <= 0))]
        pts.sort(key=lambda t: abs(t[0]))
        xs = [abs(p) for p, _ in pts]
        ys = [y for _, y in pts]
        return interp_root(xs, ys, 0.0)
    r["phi_up"] = {s: phi_cross("up", s) for s in (1, -1)}
    r["phi_dn"] = {s: phi_cross("dn", s) for s in (1, -1)}
    return r


def fmt(x, f="%.3f", none="n/a"):
    return none if x is None else (x if isinstance(x, str) else f % x)


def cmd_analyze(a):
    m = json.load(open(a.values))
    r = analyze_one(m, a.vsup)
    out = []
    P = out.append
    P(f"- Held-VWIN grid (V): {', '.join('%g' % v for v in VH)}; phase-error grid (ps): {', '.join(str(p) for p in PHI_PS)}")
    P(f"- Schmitt trip points of the cell's own `schmitt_hv`, from a {RAMP_NS} ns ramp of VWIN (3.3 -> 0 -> 3.3 V, LOCK crossing VDD/2): "
      f"LOCK rises when VWIN falls through {fmt(r['vt_dn'])} V; LOCK falls when VWIN rises through {fmt(r['vt_up'])} V")
    P(f"- Delay-window propagation delay twin (ERR 50 % -> ERRD 50 %, phi = +{max(PHI_PS)} ps): rise {fmt(r['twin_r'] and r['twin_r'] * 1e9)} ns, fall {fmt(r['twin_f'] and r['twin_f'] * 1e9)} ns")
    P("")
    P("| phi (ps) | UP (ns) | DN (ns) | ERR (ns) | ERRD (ns) | WIDE (ns) | WIDE peak (V) | I_net @ trip-up (uA) | I_net @ trip-down (uA) | V_eq (V) |")
    P("|---|---|---|---|---|---|---|---|---|---|")
    for pj, p in enumerate(PHI_PS):
        w = r["wid"][pj]
        g = lambda k: fmt(None if w[k] is None else w[k] / a.vsup * 1e9, "%.2f")
        P(f"| {p} | {g('up')} | {g('dn')} | {g('err')} | {g('errd')} | {g('wide')} | {fmt(r['wmax'][pj], '%.2f')} | "
          f"{fmt(r['inet_trip']['up'][pj], '%.3f')} | {fmt(r['inet_trip']['dn'][pj], '%.3f')} | {fmt(r['veq'][pj], '%.2f')} |")
    P("")
    P("| phi (ps) | " + " | ".join("I_net @ %g V (uA)" % v for v in VH) + " |")
    P("|---|" + "---|" * len(VH))
    for pj, p in enumerate(PHI_PS):
        P(f"| {p} | " + " | ".join(fmt(r["I"].get((vi, pj)), "%.3f") for vi in range(len(VH))) + " |")
    P("")
    for key, nm in (("phi_up", "VWIN-rising trip (LOCK falls); the phase error below which the loop's VWIN settles above it"),
                    ("phi_dn", "VWIN-falling trip (LOCK rises); the phase error above which VWIN settles below it")):
        P(f"- |phi| where net current at the {nm} is zero: +side {fmt(r[key][1], '%.0f')} ps, -side {fmt(r[key][-1], '%.0f')} ps")
    json.dump({"vt_up": r["vt_up"], "vt_dn": r["vt_dn"], "phi_up": r["phi_up"], "phi_dn": r["phi_dn"],
               "twin_r": r["twin_r"], "twin_f": r["twin_f"]}, open(a.summary, "w"))
    open(a.out, "w").write("\n".join(out) + "\n")


def cmd_summary(a):
    rep = json.load(open(a.report))
    rows = []
    for c in rep["corners"]:
        m = {x["name"]: x["value"] for x in c["measurements"] if x.get("value") is not None}
        vs = (c.get("params") or {}).get("vsup", 3.3)
        r = analyze_one(m, vs)
        rows.append((c["corner_id"], c["status"], c["temperature_c"], vs, r, len(m)))
    def f(x, k="%.2f", sc=1.0):
        return "n/a" if x is None else k % (x * sc)
    out = ["| corner | T (C) | VDD (V) | status | V_T- (V) | V_T+ (V) | twin rise (ns) | twin fall (ns) | phi at V_T+ , +side (ns) | phi at V_T+ , -side (ns) | phi at V_T- , +side (ns) | phi at V_T- , -side (ns) | meas |", "|" + "---|" * 13]
    for cid, st, t, vs, r, n in rows:
        out.append(f"| {cid.split('/')[0]} | {t} | {vs} | {st} | {f(r['vt_dn'])} | {f(r['vt_up'])} | {f(r['twin_r'], '%.2f', 1e9)} | {f(r['twin_f'], '%.2f', 1e9)} | "
                   f"{f(r['phi_up'][1], '%.2f', 1e-3)} | {f(r['phi_up'][-1], '%.2f', 1e-3)} | {f(r['phi_dn'][1], '%.2f', 1e-3)} | {f(r['phi_dn'][-1], '%.2f', 1e-3)} | {n} |")
    def ext(key, side, fn, which=None):
        v = [(r[key][side], cid) for cid, _, _, _, r, _ in rows if r[key][side] is not None]
        return v
    lines = []
    tw = [(min(x for x in (r["twin_r"], r["twin_f"]) if x is not None), cid, t) for cid, _, t, _, r, _ in rows if r["twin_r"] is not None and r["twin_f"] is not None]
    if tw:
        w = min(tw); lines.append(f"- Smallest delay-window delay over {len(tw)} corners: {w[0]*1e9:.2f} ns at {w[1].split('/')[0]}, {w[2]} C (floor: 2.5 ns)")
    for key, nm in (("phi_up", "VWIN-rising trip (LOCK falls)"), ("phi_dn", "VWIN-falling trip (LOCK rises)")):
        for side, sn in ((1, "+side"), (-1, "-side")):
            v = [(r[key][side], cid, t) for cid, _, t, _, r, _ in rows if r[key][side] is not None]
            miss = sum(1 for _, _, _, _, r, _ in rows if r[key][side] is None)
            if v:
                lo, hi = min(v), max(v)
                lines.append(f"- phi at the {nm}, {sn}: {lo[0]*1e-3:.2f} ns ({lo[0]/T_PS*100:.1f} % T_ref, {lo[1].split('/')[0]} {lo[2]} C) to {hi[0]*1e-3:.2f} ns ({hi[0]/T_PS*100:.1f} % T_ref, {hi[1].split('/')[0]} {hi[2]} C) over {len(v)} corners; no crossing inside |phi| <= 10 ns in {miss} corners")
            else:
                lines.append(f"- phi at the {nm}, {sn}: no crossing inside |phi| <= 10 ns in any of {miss} corners")
    open(a.out, "w").write("\n".join(lines) + "\n\n" + "\n".join(out) + "\n")


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    b = sp.add_parser("body"); b.add_argument("out"); b.add_argument("meas"); b.add_argument("meas_json"); b.set_defaults(f=cmd_body)
    q = sp.add_parser("request"); q.add_argument("--stage", type=int, choices=(1, 2), required=True)
    q.add_argument("--body", required=True); q.add_argument("out"); q.set_defaults(f=cmd_request)
    n = sp.add_parser("analyze"); n.add_argument("values"); n.add_argument("out"); n.add_argument("summary")
    n.add_argument("--vsup", type=float, default=3.3); n.set_defaults(f=cmd_analyze)
    m = sp.add_parser("summary"); m.add_argument("report"); m.add_argument("out"); m.set_defaults(f=cmd_summary)
    a = ap.parse_args()
    a.f(a)


if __name__ == "__main__":
    main()
